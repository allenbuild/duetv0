@dataclass
class TagDetection:
    """One AprilTag. corners_px [4,2]: RAW (distorted) image pixels, OpenCV pixel-centre convention (pupil-apriltags'
    pixel-corner values minus 0.5), in AprilTag 3 order = tag-frame corners (-s,+s), (+s,+s), (+s,-s), (-s,-s),
    s = tag_size/2 (bottom-left, bottom-right, top-right, top-left of the upright tag).
    T_cam_tag: tag -> camera (tag frame: centre origin, X right, Y down, Z into the face; module docstring), None without
    intrinsics. err_px: mean reprojection error of the 4 corners in raw pixels. T_cam_tag_alt / alt_err_px: the second
    planar-ambiguity (IPPE) solution; when alt_err_px is close to err_px (small, distant or fronto-parallel tags) the
    tag's ORIENTATION is ambiguous (its position is not)."""
    tag_id: int
    corners_px: np.ndarray
    T_cam_tag: np.ndarray | None
    err_px: float | None
    T_cam_tag_alt: np.ndarray | None = None
    alt_err_px: float | None = None
    hamming: int = 0
    decision_margin: float = float("nan")
    family: str = ""


def tag_object_points(tag_size_m: float) -> np.ndarray:
    """[4,3] tag-frame corners (metres) in detection order (TagDetection); identical to OpenCV's SOLVEPNP_IPPE_SQUARE order."""
    s = _in_range(tag_size_m, "tag_size_m", 0.005, 2.0, " (metres, edge of the black border square)") / 2
    return np.array([[-s, s, 0], [s, s, 0], [s, -s, 0], [-s, -s, 0]], float)


_TAG_DETECTORS: dict = {}
_TAG_LOCK = threading.Lock()


def _tag_detector(families: str):
    """(detector, lock) per families string; a pupil-apriltags Detector must not run detect() from two threads at once."""
    with _TAG_LOCK:
        if families not in _TAG_DETECTORS:
            import pupil_apriltags as apr
            _TAG_DETECTORS[families] = (apr.Detector(families=families, nthreads=4, quad_decimate=1.0, refine_edges=True), threading.Lock())
        return _TAG_DETECTORS[families]


def detect_tags(gray: np.ndarray, intr: Intrinsics | None, tag_size_m: float, families: str = "tag36h11") -> list[TagDetection]:
    """AprilTags in a RAW image. Detection runs on the raw pixels (undistorting the whole image crops a wide lens' field);
    the 4 corners are undistorted with the full lens model and the pose solved with SOLVEPNP_IPPE_SQUARE (both planar
    solutions kept). tag_size_m: black-border edge in metres. With intr=None only ids/corners are returned. Raises
    GeometryError when the image is not intr.width x intr.height."""
    g = _as_gray(gray, "detect_tags image")
    obj = None
    if intr is not None:
        intr.check_image(g, "detect_tags image"); obj = tag_object_points(tag_size_m)
    det, lock = _tag_detector(families)
    with lock:
        raw = det.detect(g)
    out = []
    for d in raw:
        c = np.asarray(d.corners, float).reshape(4, 2) - 0.5; sols = []  # AprilTag: (0, 0) = top-left pixel's CORNER -> OpenCV centres
        if obj is not None:
            sols = _planar_pose_candidates(obj, c, intr, cv2.SOLVEPNP_IPPE_SQUARE, refine=False)
        fam = d.tag_family.decode() if isinstance(d.tag_family, bytes) else str(d.tag_family)
        (T, e), (T2, e2) = (sols + [(None, None), (None, None)])[:2]
        out.append(TagDetection(int(d.tag_id), c, T, e, T2, e2, int(d.hamming), float(d.decision_margin), fam))
    return out


# ----------------------------------------------------------------------------- transforms

def validate_rigid(T: np.ndarray, name: str = "T", atol: float = 1e-5) -> np.ndarray:
    """T as a float64 4x4 after checking it is a proper rigid transform: finite, bottom row (0, 0, 0, 1), rotation block
    orthonormal and det +1 (absolute tolerance atol; float32-stored poses pass). Never repairs; raises GeometryError."""
    errs = rigid_matrix_errors(T, tolerance=atol)
    if errs:
        raise GeometryError(f"{name} is not a rigid transform: {'; '.join(errs)}")
    return np.array(T, dtype=float)


def rt_to_T(rvec, tvec) -> np.ndarray:
    """OpenCV (rvec, tvec) -> 4x4 T (for solvePnP output this is T_cam_obj)."""
    R, _ = cv2.Rodrigues(np.asarray(rvec, float).reshape(3, 1)); T = np.eye(4); T[:3, :3] = R; T[:3, 3] = np.asarray(tvec, float).ravel(); return T


def inv(T: np.ndarray) -> np.ndarray:
    """Inverse of a rigid transform (validated): inv(T_a_b) = T_b_a."""
    T = validate_rigid(T); R, t = T[:3, :3], T[:3, 3]; Ti = np.eye(4); Ti[:3, :3] = R.T; Ti[:3, 3] = -R.T @ t; return Ti


def apply(T: np.ndarray, p: np.ndarray) -> np.ndarray:
    """T [4,4] applied to points [..., 3]."""
    return p @ T[:3, :3].T + T[:3, 3]


def head_pose_from_tag(T_world_fixedcam: np.ndarray, T_fixedcam_tag: np.ndarray, T_tag_headcam: np.ndarray) -> np.ndarray:
    """T_world_headcam from a fixed camera seeing the head tag. T_fixedcam_tag: TagDetection.T_cam_tag. T_tag_headcam: the
    head camera's pose IN THE TAG FRAME (head-camera coords -> tag coords), measured once per rig. Example: a tag worn
    upright on the forehead facing forward with the lens 5 cm below its centre: tag X = wearer's left, Y = down, Z = into
    the head (backwards), so R_tag_headcam = diag(-1, 1, -1), t = (0, 0.05, 0). Identity is NOT a neutral default: it
    means the camera looks through the back of the tag (into its face)."""
    return (validate_rigid(T_world_fixedcam, "T_world_fixedcam") @ validate_rigid(T_fixedcam_tag, "T_fixedcam_tag")
            @ validate_rigid(T_tag_headcam, "T_tag_headcam"))


def average_rotations(Rs: np.ndarray, weights: np.ndarray | None = None) -> np.ndarray:
    """Chordal L2 mean of rotations [N,3,3]: the rotation nearest (Frobenius) to sum_i w_i R_i."""
    Rs = np.asarray(Rs, float).reshape(-1, 3, 3)
    w = np.ones(len(Rs)) if weights is None else np.asarray(weights, float).ravel()
    if len(Rs) == 0 or len(w) != len(Rs) or not np.isfinite(Rs).all() or not (w >= 0).all() or w.sum() <= 0:
        raise GeometryError("average_rotations: need >= 1 finite rotation and matching non-negative weights")
    U, _, Vt = np.linalg.svd(np.einsum("n,nij->ij", w, Rs))
    return U @ np.diag([1, 1, np.sign(np.linalg.det(U @ Vt))]) @ Vt


def fit_similarity(src: np.ndarray, dst: np.ndarray, with_scale: bool = True, min_minor_ratio: float = 0.02) -> tuple[np.ndarray, float] | None:
    """Umeyama least squares dst ~= s * R @ src + t for matched points [N,3]. Returns (T [4,4] holding R and t, s), or None
    when the rotation is undetermined: < 3 points, or src (nearly) collinear, i.e. second singular value of the centred
    points < min_minor_ratio x the first (two distinct camera centres leave the rotation about their baseline free; use
    similarity_from_camera_poses)."""
    src = np.asarray(src, float); dst = np.asarray(dst, float)
    if src.shape != dst.shape or src.ndim != 2 or src.shape[1] != 3:
        raise GeometryError(f"fit_similarity: src {src.shape} and dst {dst.shape} must both be [N, 3]")
    if len(src) < 3 or not (np.isfinite(src).all() and np.isfinite(dst).all()):
        return None
    mu_s, mu_d = src.mean(0), dst.mean(0); S, D = src - mu_s, dst - mu_d
    sv = np.linalg.svd(S, compute_uv=False)
    if sv[0] <= 0 or sv[1] < min_minor_ratio * sv[0]:
        return None
    U, sig, Vt = np.linalg.svd(D.T @ S / len(src)); Dm = np.diag([1, 1, np.sign(np.linalg.det(U @ Vt))])
    R = U @ Dm @ Vt; s = float((sig * np.diag(Dm)).sum() / ((S ** 2).sum() / len(src))) if with_scale else 1.0
    T = np.eye(4); T[:3, :3] = R; T[:3, 3] = mu_d - s * R @ mu_s
    return T, s


def similarity_from_camera_poses(T_a_cams: np.ndarray, T_b_cams: np.ndarray, with_scale: bool = True) -> tuple[np.ndarray, float] | None:
    """(T_b_a as [4,4] R|t, s) with X_b = s R X_a + t, from the SAME cameras' poses in frames a and b ([N,4,4], camera ->
    frame; e.g. a = COLMAP model, b = board world). Rotation = chordal mean of R_b_cam R_a_cam^T, so it is determined even
    by one or two cameras (unlike fit_similarity on camera centres). Scale needs >= 2 distinct centres (None otherwise
    when with_scale). Poses in a must share one scale (a similarity frame), rotations must be proper."""
    A = np.asarray(T_a_cams, float).reshape(-1, 4, 4); B = np.asarray(T_b_cams, float).reshape(-1, 4, 4)
    if len(A) != len(B) or len(A) == 0:
        raise GeometryError(f"similarity_from_camera_poses: {len(A)} vs {len(B)} poses")
    for k in range(len(A)):
        validate_rigid(A[k], f"T_a_cams[{k}]"); validate_rigid(B[k], f"T_b_cams[{k}]")
    R = average_rotations(np.einsum("nij,nkj->nik", B[:, :3, :3], A[:, :3, :3]))
    ca, cb = A[:, :3, 3], B[:, :3, 3]; ca0, cb0 = ca - ca.mean(0), cb - cb.mean(0)
    s = 1.0
    if with_scale:
        den = float((ca0 ** 2).sum())
        if den <= 1e-12 * max(1.0, float((ca ** 2).sum())):
            return None
        s = float(np.einsum("ni,ni->", cb0, ca0 @ R.T) / den)
        if not s > 0:
            return None
    T = np.eye(4); T[:3, :3] = R; T[:3, 3] = cb.mean(0) - s * R @ ca.mean(0)
    return T, s


