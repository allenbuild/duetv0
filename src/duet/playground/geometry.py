@dataclass
class Camera:
    name: str
    intr: Intrinsics
    T_world_cam: np.ndarray  # 4x4 camera -> world (validated)

    def __post_init__(self):
        self.T_world_cam = validate_rigid(self.T_world_cam, f"Camera {self.name!r} T_world_cam")

    @property
    def P(self) -> np.ndarray:
        """3x4 K [R|t]: world points -> UNDISTORTED pixel coordinates. Raw detections must be undistorted first
        (K @ undistort_points(...)) before they can be used with P."""
        T_cw = inv(self.T_world_cam); return self.intr.K @ T_cw[:3, :4]


def _tri_solve(R: np.ndarray, t: np.ndarray, f: np.ndarray, xn: np.ndarray, w: np.ndarray, mask: np.ndarray, iters: int) -> np.ndarray:
    """Weighted DLT + Gauss-Newton on (focal-scaled) normalised reprojection error for N points at once.
    R [C,3,3], t [C,3]: world -> camera; f [C] px; xn [C,N,2] undistorted normalised obs; w [C,N] weights; mask [C,N]."""
    C, N = mask.shape
    s = np.where(mask, np.sqrt(np.clip(np.where(mask, w, 0.0), 0, None)) * f[:, None], 0.0)
    x = np.where(mask[..., None], xn, 0.0)
    P = np.concatenate([R, t[:, :, None]], axis=2)
    r1 = x[..., 0, None] * P[:, None, 2, :] - P[:, None, 0, :]
    r2 = x[..., 1, None] * P[:, None, 2, :] - P[:, None, 1, :]
    A = np.transpose(np.concatenate([r1 * s[..., None], r2 * s[..., None]], axis=0), (1, 0, 2))  # [N, 2C, 4]
    X = np.full((N, 3), np.nan); ok = mask.sum(0) >= 2
    if not ok.any():
        return X
    Xh = np.linalg.svd(A[ok])[2][:, -1, :]
    hw = Xh[:, 3]; fin = np.abs(hw) > 1e-9 * np.linalg.norm(Xh[:, :3], axis=1)  # |w| ~ 0: rays (nearly) parallel -> infinity
    Xo = np.full((ok.sum(), 3), np.nan); Xo[fin] = Xh[fin, :3] / hw[fin, None]; X[ok] = Xo
    live = np.isfinite(X).all(1)
    with np.errstate(over="ignore", invalid="ignore"):  # points diverging to infinity are rejected by the caller's range check
        for _ in range(iters):
            if not live.any():
                break
            Xc = np.einsum("cij,nj->cni", R, np.where(live[:, None], X, 0.0)) + t[:, None, :]
            z = Xc[..., 2]; g = mask & (z > 1e-9); zi = np.where(g, 1.0 / np.where(g, z, 1.0), 0.0)
            u, v = Xc[..., 0] * zi, Xc[..., 1] * zi; sg = s * g
            res = np.stack([u - x[..., 0], v - x[..., 1]], -1) * sg[..., None]
            Jc = np.zeros((C, N, 2, 3)); Jc[..., 0, 0] = zi; Jc[..., 0, 2] = -u * zi; Jc[..., 1, 1] = zi; Jc[..., 1, 2] = -v * zi
            J = np.einsum("cnij,cjk->cnik", Jc, R) * sg[..., None, None]
            H = np.einsum("cnij,cnik->njk", J, J); gr = np.einsum("cnij,cni->nj", J, res)
            H = H + (1e-12 * np.trace(H, axis1=1, axis2=2) + 1e-300)[:, None, None] * np.eye(3)
            upd = live & (g.sum(0) >= 2) & np.isfinite(H).all((1, 2)) & np.isfinite(gr).all(1)
            if not upd.any():
                break
            dX = np.zeros((N, 3))
            try:
                dX[upd] = -np.linalg.solve(H[upd], gr[upd][..., None])[..., 0]
            except np.linalg.LinAlgError:
                dX[upd] = -np.einsum("nij,nj->ni", np.linalg.pinv(H[upd]), gr[upd])
            X = np.where(live[:, None], X + dX, X)
            if not np.abs(dX[upd]).max() >= 1e-10:
                break
    return X


def _tri_core(cams: list[Camera], pts: np.ndarray, wts: np.ndarray, *, outlier_px: float | None, min_angle_deg: float, max_range_m: float,
              refine: bool) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """-> X [N,3], mean raw-px error over used views [N], used [C,N]; X/E NaN (used all False) where rejected."""
    C, N = wts.shape
    Tcw = [inv(c.T_world_cam) for c in cams]
    R = np.stack([T[:3, :3] for T in Tcw]); t = np.stack([T[:3, 3] for T in Tcw]); centres = np.stack([c.T_world_cam[:3, 3] for c in cams])
    f = np.array([np.sqrt(c.intr.K[0, 0] * c.intr.K[1, 1]) for c in cams])
    valid = np.isfinite(wts) & (wts > 0) & np.isfinite(pts).all(-1)
    xn = np.full((C, N, 2), np.nan)
    for c in range(C):
        if valid[c].any():
            xn[c, valid[c]] = undistort_points(cams[c].intr, pts[c, valid[c]])
    valid &= np.isfinite(xn).all(-1)
    iters = 10 if refine else 0

    def errors(X):
        Xc = np.einsum("cij,nj->cni", R, X) + t[:, None, :]
        e = np.stack([np.linalg.norm(project_cam(cams[c].intr, Xc[c]) - pts[c], axis=1) for c in range(C)])
        return e, Xc[..., 2]

    used = valid.copy(); X = _tri_solve(R, t, f, xn, wts, used, iters); E_c, depth = errors(X)
    if outlier_px is not None and C >= 3:
        # the joint fit spreads an outlier over all views (30 px in 1 of 3 views shows as ~12 px), so check consensus early
        need = (valid.sum(0) >= 3) & (valid & ~(E_c <= outlier_px / 3)).any(0)
        if need.any():  # MSAC over all view pairs (exhaustive; C is small), then refit on the best hypothesis' inliers
            best_n = np.zeros(N, int); best_cost = np.full(N, np.inf); best = np.zeros_like(valid)
            for a, b in combinations(range(C), 2):
                m = np.zeros_like(valid); m[a] = valid[a] & valid[b] & need; m[b] = m[a]
                if not m[a].any():
                    continue
                Ep, dp = errors(_tri_solve(R, t, f, xn, wts, m, iters))
                inl = valid & (Ep <= outlier_px) & (dp > _MIN_DEPTH_M)
                cost = np.where(valid, np.minimum(np.where(inl, Ep, outlier_px), outlier_px) ** 2, 0).sum(0)
                better = m[a] & (inl.sum(0) >= 2) & (cost < best_cost)
                best_n[better], best_cost[better] = inl.sum(0)[better], cost[better]; best[:, better] = inl[:, better]
            redo = need & (best_n >= 2)
            if redo.any():
                used[:, redo] = best[:, redo]
                Xr = _tri_solve(R, t, f, xn, wts, used & redo[None], iters); X[redo] = Xr[redo]
                E_c, depth = errors(X)
    n_used = used.sum(0)
    dist = np.linalg.norm(X[None] - centres[:, None], axis=-1)
    d = (X[None] - centres[:, None]) / np.where(dist > 0, dist, np.nan)[..., None]
    cosm = np.einsum("anj,bnj->nab", d, d)
    pair = used.T[:, :, None] & used.T[:, None, :] & ~np.eye(C, dtype=bool)[None]
    min_cos = np.where(pair, np.nan_to_num(cosm, nan=1.0), 1.0).min(axis=(1, 2))
    with np.errstate(invalid="ignore"):
        E = np.where(used, E_c, 0).sum(0) / np.maximum(n_used, 1)
        ok = ((n_used >= 2) & np.isfinite(X).all(1) & np.isfinite(E) & np.all(~used | (depth > _MIN_DEPTH_M), axis=0)
              & np.all(~used | (dist <= max_range_m), axis=0) & (np.degrees(np.arccos(np.clip(min_cos, -1, 1))) >= min_angle_deg))
    X[~ok] = np.nan; E = np.where(ok, E, np.nan); used[:, ~ok] = False
    return X, E, used


def triangulate(cams: list[Camera], pts_px: list[np.ndarray | None], weights: list[float] | None = None, *, outlier_px: float | None = 12.0,
                min_angle_deg: float = 2.0, max_range_m: float = 10.0, refine: bool = True) -> tuple[np.ndarray, float] | None:
    """One point from >= 2 views. pts_px: per camera a RAW pixel [2] or None (same length as cams). Returns (X_world [3],
    mean raw-px reprojection error over the views used) or None when fewer than 2 usable views remain, the point is
    behind a used camera, farther than max_range_m from one, or all ray pairs meet at < min_angle_deg. With >= 3 views a
    view inconsistent with the others by > outlier_px is dropped. weights (e.g. detector confidence) scale each view."""
    if len(pts_px) != len(cams) or (weights is not None and len(weights) != len(cams)):
        raise GeometryError(f"triangulate: {len(cams)} cameras but {len(pts_px)} observations" + ("" if weights is None else f" / {len(weights)} weights"))
    C = len(cams); pts = np.full((C, 1, 2), np.nan); w = np.zeros((C, 1))
    for c, p in enumerate(pts_px):
        if p is not None:
            a = np.asarray(p, float).ravel()
            if a.shape != (2,):
                raise GeometryError(f"triangulate: observation {c} has shape {np.shape(p)}, expected [2]")
            pts[c, 0] = a; w[c, 0] = 1.0 if weights is None else float(weights[c])
    X, E, _ = _tri_core(cams, pts, w, outlier_px=outlier_px, min_angle_deg=min_angle_deg, max_range_m=max_range_m, refine=refine)
    return None if not np.isfinite(E[0]) else (X[0], float(E[0]))


def triangulate_many(cams: list[Camera], pts: np.ndarray, conf: np.ndarray, min_conf: float = 0.4, max_err_px: float | None = 25.0, *,
                     outlier_px: float | None = None, min_angle_deg: float = 2.0, max_range_m: float = 10.0, refine: bool = True,
                     return_used: bool = False):
    """pts [C, N, 2] RAW pixels per camera per point, conf [C, N] (views with conf < min_conf or non-finite pixels are
    unused; the rest are weighted by conf). Returns X [N, 3] (world, metres) and err [N] (mean raw-px reprojection error
    over the used views), NaN where rejected: see triangulate, plus err > max_err_px. outlier_px (default max_err_px / 2,
    12 px without a gate) is the per-view consistency threshold for dropping views when >= 3 are available.
    return_used=True also returns used [C, N] (bool)."""
    pts = np.asarray(pts, float); conf = np.asarray(conf, float)
    if conf.ndim != 2 or pts.shape != (*conf.shape, 2) or conf.shape[0] != len(cams):
        raise GeometryError(f"triangulate_many: pts {pts.shape} / conf {conf.shape} must be [C, N, 2] / [C, N] with C = {len(cams)} cameras")
    if outlier_px is None:
        outlier_px = 12.0 if max_err_px is None else max_err_px / 2
    w = np.where(conf >= min_conf, conf, 0.0)
    X, E, used = _tri_core(cams, pts, w, outlier_px=outlier_px, min_angle_deg=min_angle_deg, max_range_m=max_range_m, refine=refine)
    if max_err_px is not None:
        bad = ~(E <= max_err_px); X[bad] = np.nan; E[bad] = np.nan; used[:, bad] = False
    return (X, E, used) if return_used else (X, E)


