@dataclass
class Intrinsics:
    """Intrinsics for images of exactly width x height pixels. K: 3x3 (px). dist: per `model` (module docstring).
    source: provenance, e.g. "board", "rig_json", "zed_factory", "nominal_fov" (a guess, not a calibration)."""
    K: np.ndarray
    dist: np.ndarray
    width: int
    height: int
    model: str = "pinhole"
    source: str = ""
    rms_px: float | None = None

    def __post_init__(self):
        if not isinstance(self.model, str) or self.model not in LENS_MODELS:
            raise GeometryError(f"Intrinsics.model={self.model!r}: expected one of {LENS_MODELS}")
        K = np.array(self.K, dtype=float)
        d = np.array([] if self.dist is None else self.dist, dtype=float).ravel()
        if K.shape != (3, 3) or not np.isfinite(K).all() or K[0, 0] <= 0 or K[1, 1] <= 0 or abs(K[1, 0]) > 1e-9 * K[1, 1] or not np.allclose(K[2], [0, 0, 1]):
            raise GeometryError(f"Intrinsics.K must be a finite 3x3 camera matrix with fx, fy > 0 and last row [0, 0, 1]; got {K.tolist()}")
        if d.size == 0:
            d = np.zeros(4 if self.model == "fisheye" else 5)
        if not np.isfinite(d).all() or (d.size != 4 if self.model == "fisheye" else d.size not in (4, 5, 8, 12, 14)):
            raise GeometryError(f"Intrinsics.dist has {d.size} coefficients {d.tolist()}: model {self.model!r} takes "
                                f"{'4 (k1..k4)' if self.model == 'fisheye' else '4, 5, 8, 12 or 14 (OpenCV order)'}")
        w, h = self.width, self.height
        if isinstance(w, bool) or isinstance(h, bool) or not float(w).is_integer() or not float(h).is_integer() or int(w) <= 0 or int(h) <= 0:
            raise GeometryError(f"Intrinsics.width/height must be positive integers, got {w!r} x {h!r}")
        self.K, self.dist, self.width, self.height = K, d, int(w), int(h)
        self.rms_px = None if self.rms_px is None else float(self.rms_px)

    def to_json(self) -> dict:
        return {"K": self.K.tolist(), "dist": self.dist.ravel().tolist(), "width": self.width, "height": self.height, "model": self.model,
                "source": self.source, "rms_px": self.rms_px}

    @classmethod
    def from_json(cls, d: dict) -> Intrinsics:
        """Also reads files written before model/source existed: then the model follows OpenCV's own reading of the
        coefficient vector (<= 5 -> "pinhole", 8/12/14 -> "rational"); a fisheye lens must be declared explicitly. "dist"
        is required ([] = none): a missing key is not taken to mean an ideal lens."""
        if "dist" not in d or "K" not in d:
            raise GeometryError(f"intrinsics JSON needs 'K' and 'dist' (use [] for no distortion); got keys {sorted(d)}")
        dist = np.array(d["dist"] if d["dist"] is not None else [], float).ravel()
        model = d.get("model") or ("pinhole" if dist.size <= 5 else "rational")
        return cls(np.array(d["K"], float), dist, int(d["width"]), int(d["height"]), model, str(d.get("source") or ""), d.get("rms_px"))

    @classmethod
    def nominal(cls, width: int, height: int, fov_deg: float, axis: str = "horizontal", model: str = "pinhole") -> Intrinsics:
        """A GUESS from a quoted field of view (source="nominal_fov"): no distortion, principal point at the image centre.
        axis: image extent the FOV spans ("horizontal" = width, "vertical" = height, "diagonal"). model: "pinhole"
        (rectilinear lens, FOV < 180) or "fisheye" (equidistant r = f * theta). GoPro-class FOVs describe fisheye-like
        lenses: a pinhole with the same 120 deg HFOV over 1280 px has f = 369 px where the lens centre has ~611 px."""
        half = {"horizontal": width / 2, "vertical": height / 2, "diagonal": float(np.hypot(width, height)) / 2}.get(axis)
        if half is None:
            raise GeometryError(f"nominal: axis={axis!r} must be 'horizontal', 'vertical' or 'diagonal'")
        th = np.radians(_in_range(fov_deg, "fov_deg", 1.0, 179.0 if model == "pinhole" else 240.0)) / 2
        if model == "pinhole":
            f = half / np.tan(th)
        elif model == "fisheye":
            f = half / th
        else:
            raise GeometryError(f"nominal: model={model!r} must be 'pinhole' or 'fisheye'")
        K = np.array([[f, 0, (width - 1) / 2], [0, f, (height - 1) / 2], [0, 0, 1]], float)
        return cls(K, np.zeros(4 if model == "fisheye" else 5), width, height, model, "nominal_fov")

    def scaled_to(self, width: int, height: int) -> Intrinsics:
        """The same camera for images RESIZED from (self.width, self.height) to (width, height), e.g. a rig.json K at the
        native 1920x1080 -> 640x360 extracted frames. Pixel-centre convention u' = (u + 0.5) * s - 0.5; distortion acts on
        normalised coordinates and is unchanged. Raises GeometryError when the aspect ratio differs by > 1 % (a crop or a
        different sensor mode, which K alone cannot describe)."""
        sx, sy = width / self.width, height / self.height
        if not (sx > 0 and sy > 0) or abs(sx / sy - 1) > 0.01:
            raise GeometryError(f"scaled_to: {self.width}x{self.height} -> {width}x{height} changes the aspect ratio by "
                                f"{100 * abs(sx / sy - 1):.1f} % (> 1 %): not a resize of the calibrated image")
        K = self.K.copy()
        K[0, :2] *= sx; K[1, 1] *= sy; K[0, 2] = (K[0, 2] + 0.5) * sx - 0.5; K[1, 2] = (K[1, 2] + 0.5) * sy - 0.5
        rms = None if self.rms_px is None else self.rms_px * (sx + sy) / 2
        return Intrinsics(K, self.dist.copy(), int(width), int(height), self.model, self.source, rms)

    def check_image(self, img, what: str = "image") -> None:
        """Raise GeometryError unless img is height x width (the frame-size contract)."""
        h, w = np.asarray(img).shape[:2]
        if (h, w) != (self.height, self.width):
            raise GeometryError(f"{what} is {w}x{h} but the intrinsics ({self.source or 'unknown source'}) are for {self.width}x{self.height}; "
                                "rescale them with Intrinsics.scaled_to()")


@lru_cache(maxsize=256)
def _max_radius(model: str, dist: tuple) -> float:
    """Largest normalised radius |(X/Z, Y/Z)| up to which the model's radial mapping is monotonic. Beyond it a
    polynomial model folds back (rays far outside the calibrated field land inside the image). Tangential terms ignored."""
    if model == "fisheye":
        th = np.linspace(0, np.pi / 2 - 1e-3, 8001)[1:]
        k = np.asarray(dist, float); t2 = th * th
        thd = th * (1 + t2 * (k[0] + t2 * (k[1] + t2 * (k[2] + t2 * k[3]))))
        bad = np.nonzero(np.diff(thd) <= 0)[0]
        return float(np.tan(th[bad[0]])) if len(bad) else np.inf
    d = np.zeros(8); d[:min(8, len(dist))] = np.asarray(dist, float)[:8]
    k1, k2, _, _, k3, k4, k5, k6 = d
    r = np.linspace(0, 20.0, 40001)[1:]; r2 = r * r
    den = 1 + r2 * (k4 + r2 * (k5 + r2 * k6))
    rd = r * (1 + r2 * (k1 + r2 * (k2 + r2 * k3))) / np.where(den > 0, den, np.nan)
    bad = np.nonzero(~(np.diff(rd) > 0))[0]
    return float(r[bad[0]]) if len(bad) else np.inf


def _project_normalized(intr: Intrinsics, xy: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Normalised points (x, y) [M,2] -> raw pixels [M,2] and d(u, v)/d(x, y) [M,2,2] (OpenCV's own model + Jacobian)."""
    P = np.c_[xy, np.ones(len(xy))].reshape(-1, 1, 3); z = np.zeros(3)
    if intr.model == "fisheye":
        uv, jac = cv2.fisheye.projectPoints(P, z, z, intr.K, intr.dist.reshape(4, 1)); cols = slice(11, 13)
    else:
        uv, jac = cv2.projectPoints(P, z, z, intr.K, intr.dist); cols = slice(3, 5)
    return uv.reshape(-1, 2), np.asarray(jac)[:, cols].reshape(-1, 2, 2)


def undistort_points(intr: Intrinsics, px: np.ndarray) -> np.ndarray:
    """RAW (distorted) pixels [..., 2] -> undistorted NORMALISED image coordinates [..., 2] = (X/Z, Y/Z) in the camera
    frame (multiply by K for undistorted pixels; (x, y, 1) * Z is the camera-frame point at depth Z). OpenCV's iterative
    solve with explicit criteria, polished by Newton steps on the forward model and verified (re-projects within 1e-3 px).
    NaN where the input is not finite or the lens model cannot be inverted (beyond its monotonic range)."""
    p = np.asarray(px, dtype=float)
    if p.ndim == 0 or p.shape[-1] != 2:
        raise GeometryError(f"undistort_points: expected [..., 2] pixels, got shape {p.shape}")
    flat = p.reshape(-1, 2); out = np.full(flat.shape, np.nan); ok = np.isfinite(flat).all(1)
    if ok.any():
        src = flat[ok]; s = src.reshape(-1, 1, 2)
        if intr.model == "fisheye":
            n = cv2.fisheye.undistortPoints(s, intr.K, intr.dist.reshape(4, 1), criteria=_CRITERIA)
        elif hasattr(cv2, "undistortPointsIter"):  # OpenCV 4.x: plain undistortPoints stops after 5 iterations
            n = cv2.undistortPointsIter(s, intr.K, intr.dist, None, None, _CRITERIA)
        else:  # OpenCV 5: undistortPoints takes the criteria
            n = cv2.undistortPoints(s, intr.K, intr.dist, criteria=_CRITERIA)
        n = np.asarray(n, float).reshape(-1, 2)
        lin = (src - intr.K[:2, 2]) / np.diag(intr.K)[:2]
        n = np.where(np.isfinite(n), n, lin)
        for _ in range(4):
            uv, J = _project_normalized(intr, n); r = src - uv
            det = J[:, 0, 0] * J[:, 1, 1] - J[:, 0, 1] * J[:, 1, 0]
            safe = np.abs(det) > 1e-12
            step = np.zeros_like(n)
            step[safe, 0] = (J[safe, 1, 1] * r[safe, 0] - J[safe, 0, 1] * r[safe, 1]) / det[safe]
            step[safe, 1] = (-J[safe, 1, 0] * r[safe, 0] + J[safe, 0, 0] * r[safe, 1]) / det[safe]
            n = n + step
        uv, _ = _project_normalized(intr, n)
        good = np.isfinite(n).all(1) & (np.linalg.norm(uv - src, axis=1) < 1e-3) & (np.hypot(n[:, 0], n[:, 1]) < _max_radius(intr.model, tuple(intr.dist)))
        res = np.full_like(n, np.nan); res[good] = n[good]; out[ok] = res
    return out.reshape(p.shape)


def project_cam(intr: Intrinsics, pts_cam: np.ndarray) -> np.ndarray:
    """Camera-frame points [..., 3] (metres) -> RAW pixels [M, 2]. NaN for points at depth <= 0, non-finite points and
    rays beyond the lens model's monotonic range (where a polynomial model would fold them back into the image)."""
    Xc = np.asarray(pts_cam, float).reshape(-1, 3); out = np.full((len(Xc), 2), np.nan)
    ok = np.isfinite(Xc).all(1) & (Xc[:, 2] > 1e-9)
    if ok.any():
        idx = np.nonzero(ok)[0]
        idx = idx[np.hypot(Xc[idx, 0], Xc[idx, 1]) / Xc[idx, 2] < _max_radius(intr.model, tuple(intr.dist))]
        if len(idx):
            out[idx] = _project_normalized(intr, Xc[idx, :2] / Xc[idx, 2:3])[0]
    return out


def project(intr: Intrinsics, T_cam_world: np.ndarray, pts_world: np.ndarray) -> np.ndarray:
    """World points [..., 3] -> RAW pixels [M, 2] for a camera with pose T_cam_world (world -> camera). NaN where the
    point is behind the camera or outside the lens model's range (see project_cam)."""
    T = validate_rigid(T_cam_world, "T_cam_world")
    X = np.asarray(pts_world, float).reshape(-1, 3)
    return project_cam(intr, X @ T[:3, :3].T + T[:3, 3])


# ----------------------------------------------------------------------------- planar poses (board, tags)

def _planar_pose_candidates(obj: np.ndarray, px: np.ndarray, intr: Intrinsics, flags: int, refine: bool) -> list[tuple[np.ndarray, float]]:
    """PnP for planar object points (z = 0) on undistorted normalised coordinates -> [(T_cam_obj, mean raw-px error)],
    best first; only solutions with every point in front of the camera and finite errors."""
    n = undistort_points(intr, px); ok = np.isfinite(n).all(1)
    if ok.sum() < 4:
        return []
    o, nn, pp = obj[ok].astype(np.float64), n[ok].astype(np.float64), px[ok].astype(np.float64)
    try:
        _, rvecs, tvecs, _ = cv2.solvePnPGeneric(o, nn, np.eye(3), None, flags=flags)
    except cv2.error:
        return []
    out = []
    for rv, tv in zip(rvecs, tvecs):
        if refine:
            try:  # ML refinement: pixel space through the full model; fisheye in normalised space (no fisheye LM in OpenCV)
                rv, tv = (cv2.solvePnPRefineLM(o, pp, intr.K, intr.dist, rv.copy(), tv.copy()) if intr.model != "fisheye"
                          else cv2.solvePnPRefineLM(o, nn, np.eye(3), None, rv.copy(), tv.copy()))
            except cv2.error:
                pass
        if not (np.isfinite(rv).all() and np.isfinite(tv).all()):
            continue
        T = rt_to_T(rv, tv); Xc = o @ T[:3, :3].T + T[:3, 3]
        if (Xc[:, 2] <= _MIN_DEPTH_M).any():
            continue
        e = np.linalg.norm(project_cam(intr, Xc) - pp, axis=1)
        if np.isfinite(e).all():
            out.append((T, float(e.mean())))
    return sorted(out, key=lambda s: s[1])


def pose_from_board_corners(corners: np.ndarray, ids: np.ndarray, intr: Intrinsics, spec: BoardSpec, max_err_px: float = 10.0) -> tuple[np.ndarray, float] | None:
    """T_cam_board and mean reprojection error (raw px) from detected ChArUco corners (RAW pixels) and ids. None when
    degenerate: < 6 corners, (nearly) collinear corners (rotation about the line is free), non-finite values, a solution
    behind the camera, or mean error > max_err_px."""
    img = np.asarray(corners, float).reshape(-1, 2); ids = np.asarray(ids).ravel().astype(int)
    if len(img) != len(ids):
        raise GeometryError(f"{len(img)} corners but {len(ids)} ids")
    cc = _board_corners(spec)
    if len(ids) and (ids.min() < 0 or ids.max() >= len(cc)):
        raise GeometryError(f"ChArUco ids {ids.min()}..{ids.max()} do not belong to a {spec.squares_x}x{spec.squares_y} board")
    if len(ids) < 6 or not np.isfinite(img).all():
        return None
    obj = cc[ids]
    if _minor_extent(obj[:, :2]) < 0.25 * spec.square_m:
        return None
    cands = _planar_pose_candidates(obj, img, intr, cv2.SOLVEPNP_IPPE, refine=True)
    if not cands or cands[0][1] > max_err_px:
        return None
    return cands[0]


def board_pose(gray: np.ndarray, intr: Intrinsics, spec: BoardSpec, max_err_px: float = 10.0) -> tuple[np.ndarray, float] | None:
    """T_cam_board (board -> camera, metres) from one RAW image, plus the mean reprojection error in raw pixels; None if
    the board is not seen or the view is degenerate (pose_from_board_corners). Raises GeometryError when the image is not
    intr.width x intr.height."""
    g = _as_gray(gray, "board_pose image"); intr.check_image(g, "board_pose image")
    c, i = detect_board(g, spec)
    return None if c is None else pose_from_board_corners(c, i, intr, spec, max_err_px)


def _fisheye_flag(name: str) -> int:
    """cv2.fisheye.CALIB_* on OpenCV 4.x; unified into cv2.CALIB_* (with other values) on 5.x."""
    v = getattr(cv2.fisheye, name, None)
    return int(v if v is not None else getattr(cv2, name))


# per model: flag sets tried in order; the later ones drop the highest radial terms when a fit folds or has a pole
_FIT_ATTEMPTS = {"pinhole": ((), ("CALIB_FIX_K3",)), "rational": (("CALIB_RATIONAL_MODEL",), ("CALIB_RATIONAL_MODEL", "CALIB_FIX_K5", "CALIB_FIX_K6")),
                 "fisheye": ((), ("CALIB_FIX_K3", "CALIB_FIX_K4"))}


def _calibrate_once(model: str, obj: list, img: list, size: tuple[int, int], extra: tuple = ()):
    """-> (K, dist, rvecs, tvecs, std [fx, fy, cx, cy] or None) or None if OpenCV fails."""
    crit = (cv2.TERM_CRITERIA_COUNT | cv2.TERM_CRITERIA_EPS, 200, 1e-12)
    try:
        if model == "fisheye":
            flags = 0
            for n in ("CALIB_RECOMPUTE_EXTRINSIC", "CALIB_FIX_SKEW", *extra):
                flags |= _fisheye_flag(n)
            o = [x.reshape(1, -1, 3).astype(np.float64) for x in obj]; i = [x.reshape(1, -1, 2).astype(np.float64) for x in img]  # (1,N,C) or it fails
            _, K, D, rv, tv = cv2.fisheye.calibrate(o, i, size, np.eye(3), np.zeros((4, 1)), flags=flags, criteria=crit)
            return K, np.asarray(D, float).ravel(), rv, tv, None
        flags = 0
        for n in extra:
            flags |= int(getattr(cv2, n))
        o = [x.astype(np.float32) for x in obj]; i = [x.reshape(-1, 1, 2).astype(np.float32) for x in img]
        _, K, D, rv, tv, std, _, _ = cv2.calibrateCameraExtended(o, i, size, None, None, flags=flags, criteria=crit)
        D = np.asarray(D, float).ravel()
        return K, (D[:8] if D.size > 8 and not D[8:].any() else D), rv, tv, np.asarray(std, float).ravel()[:4]  # rational: 14 -> 8 when unused
    except cv2.error:
        return None


def _cam_points(obj: np.ndarray, rvec, tvec) -> np.ndarray:
    return obj @ rt_to_T(rvec, tvec)[:3, :3].T + np.asarray(tvec, float).ravel()


def _fit_model(model: str, obj: list, img: list, size: tuple[int, int]):
    """Fit `model`, retrying with fewer radial terms while the fitted radial mapping folds back or has a pole inside the
    field covered by the data (an over-parameterised fit, e.g. a near pole-zero cancellation of the rational model).
    -> (Intrinsics, rvecs, tvecs, std or None, flags used) or None."""
    for extra in _FIT_ATTEMPTS[model]:
        fit = _calibrate_once(model, obj, img, size, extra)
        if fit is None:
            continue
        K, dist, rv, tv, std = fit
        try:
            intr = Intrinsics(K, dist, size[0], size[1], model, "board")
        except GeometryError:
            continue
        Xc = [_cam_points(o, r, t) for o, r, t in zip(obj, rv, tv)]
        if min(float(x[:, 2].min()) for x in Xc) <= 0:
            continue
        r_data = max(float((np.hypot(x[:, 0], x[:, 1]) / x[:, 2]).max()) for x in Xc)
        if 1.05 * r_data < _max_radius(model, tuple(intr.dist)):
            return intr, rv, tv, std, list(extra)
    return None


def _rms(intr: Intrinsics, obj: list, img: list, rvecs, tvecs) -> tuple[float, list[float]]:
    """Overall and per-view RMS reprojection error (raw px); inf where a point cannot be projected."""
    errs = [project_cam(intr, _cam_points(o, r, t)) - im for o, im, r, t in zip(obj, img, rvecs, tvecs)]
    per = [float(np.sqrt(np.mean(np.sum(e ** 2, axis=1)))) if np.isfinite(e).all() else np.inf for e in errs]
    e = np.concatenate(errs)
    return (float(np.sqrt(np.mean(np.sum(e ** 2, axis=1)))) if np.isfinite(e).all() else np.inf), per


def _std_from_jacobian(intr: Intrinsics, obj: list, img: list, rvecs, tvecs) -> np.ndarray:
    """1-sigma of (fx, fy, cx, cy) from the Gauss-Newton normal matrix of all reprojection residuals (used for fisheye,
    where OpenCV reports none). inf when the problem is singular."""
    n_int = 8 if intr.model == "fisheye" else 4 + intr.dist.size
    M = sum(len(o) for o in obj); P = n_int + 6 * len(obj)
    J = np.zeros((2 * M, P)); res = []; row = 0
    for v, (o, im) in enumerate(zip(obj, img)):
        o3 = o.reshape(-1, 1, 3).astype(np.float64); k = len(o)
        if intr.model == "fisheye":
            uv, jac = cv2.fisheye.projectPoints(o3, rvecs[v], tvecs[v], intr.K, intr.dist.reshape(4, 1))
            J[row:row + 2 * k, :8] = jac[:, :8]; J[row:row + 2 * k, n_int + 6 * v:n_int + 6 * v + 6] = jac[:, 8:14]
        else:
            uv, jac = cv2.projectPoints(o3, rvecs[v], tvecs[v], intr.K, intr.dist)
            J[row:row + 2 * k, :4] = jac[:, 6:10]; J[row:row + 2 * k, 4:n_int] = jac[:, 10:10 + intr.dist.size]
            J[row:row + 2 * k, n_int + 6 * v:n_int + 6 * v + 6] = jac[:, :6]
        res.append(uv.reshape(-1, 2) - im.reshape(-1, 2)); row += 2 * k
    r = np.concatenate(res).ravel(); dof = max(1, len(r) - P)
    try:
        with np.errstate(all="ignore"):  # some macOS BLAS builds raise spurious FP flags in matmul; finiteness is checked below
            d = np.diag(np.linalg.inv(J.T @ J))[:4] * (r @ r) / dof
    except np.linalg.LinAlgError:
        return np.full(4, np.inf)
    return np.where(np.isfinite(d) & (d >= 0), np.sqrt(np.abs(d)), np.inf)


def calibrate_intrinsics_report(frames: list[np.ndarray], spec: BoardSpec, model: str = "pinhole", **kw) -> tuple[Intrinsics | None, dict]:
    """Intrinsics from RAW grayscale views of a board seen from DIFFERENT ORIENTATIONS (moving board or moving camera),
    plus a JSON-able report (see calibrate_from_corners_report for the acceptance checks and the reason)."""
    frames = list(frames)
    if not frames:
        return None, {"model": model, "n_frames": 0, "ok": False, "reason": "no frames"}
    shapes = {np.asarray(f).shape[:2] for f in frames}
    if len(shapes) != 1:
        raise GeometryError(f"calibration frames differ in size: {sorted(shapes)}")
    h, w = shapes.pop(); det = [detect_board(g, spec, min_corners=kw.get("min_corners", 8)) for g in frames]
    intr, rep = calibrate_from_corners_report([c for c, _ in det], [i for _, i in det], (w, h), spec, model, **kw)
    rep["n_frames"] = len(frames)
    return intr, rep


def calibrate_from_corners_report(corners: list, ids: list, image_size: tuple[int, int], spec: BoardSpec, model: str = "pinhole", *,
                                  min_views: int = 8, min_corners: int = 8, min_tilt_deg: float = 15.0, max_rms_px: float = 1.0,
                                  max_rel_std_f: float = 0.01, max_std_c_frac: float = 0.01) -> tuple[Intrinsics | None, dict]:
    """Calibration from per-view ChArUco detections (corners [N,1,2] or [N,2] RAW px, ids [N]; None entries = no board).
    image_size = (width, height). Returns (None, report) with report["reason"] instead of a confident wrong answer when:
    fewer than min_views views with >= min_corners non-collinear corners; no 3 views whose board normals differ pairwise
    by >= min_tilt_deg (a fixed camera watching the board slide on one table plane cannot determine f or the principal
    point); final RMS > max_rms_px; 1-sigma of fx/fy > max_rel_std_f * f or of cx/cy > max_std_c_frac * image size;
    principal point outside the central 60 %; a pinhole fit > 10 % worse than a rational fit of the same views (wide lens);
    OpenCV failure. Views whose RMS exceeds max(3 x median, 0.5 px) are dropped (report["dropped_views"] = their indices)
    and the fit repeated; fits whose radial mapping folds inside the data are retried with fewer radial terms
    (report["flags"]). report["coverage"] (fraction of an 8x6 image grid holding corners) and ["max_radius_frac"] tell how
    much of the field the calibration actually constrains: outside it the model is extrapolated."""
    if model not in LENS_MODELS:
        raise GeometryError(f"calibrate_intrinsics: model={model!r} not in {LENS_MODELS}")
    if len(corners) != len(ids):
        raise GeometryError(f"{len(corners)} corner sets but {len(ids)} id sets")
    w, h = int(image_size[0]), int(image_size[1])
    rep: dict = {"model": model, "n_frames": len(corners), "n_views": 0, "n_used": 0, "dropped_views": [], "rms_px": None, "per_view_rms_px": [],
                 "std_px": None, "max_tilt_deg": None, "tilt_ok": False, "ok": False, "reason": ""}
    cc = _board_corners(spec); views = []
    for k, (c, i) in enumerate(zip(corners, ids)):
        if c is None or i is None:
            continue
        c = np.asarray(c, float).reshape(-1, 2); i = np.asarray(i).ravel().astype(int)
        if len(c) != len(i) or (len(i) and (i.min() < 0 or i.max() >= len(cc))):
            raise GeometryError(f"view {k}: {len(c)} corners / {len(i)} ids not from a {spec.squares_x}x{spec.squares_y} board")
        if len(i) >= min_corners and np.isfinite(c).all() and _minor_extent(cc[i, :2]) >= 0.5 * spec.square_m:
            views.append((k, cc[i], c))
    rep["n_views"] = len(views)
    if len(views) < min_views:
        rep["reason"] = f"board seen well in {len(views)} of {len(corners)} frames (need >= {min_views})"; return None, rep
    keep = list(range(len(views)))
    while True:  # refit until no view is inconsistent (at most half of the views are ever dropped)
        obj, img = [views[j][1] for j in keep], [views[j][2] for j in keep]
        fit = _fit_model(model, obj, img, (w, h))
        if fit is None:
            rep["reason"] = f"OpenCV {model} calibration failed or folded inside the data's field of view"; return None, rep
        intr, rvecs, tvecs, std, flags = fit
        rms, per_view = _rms(intr, obj, img, rvecs, tvecs)
        thr = max(3 * float(np.median(per_view)), 0.5)
        bad = [j for j, e in zip(keep, per_view) if not e <= thr]
        if not bad or len(keep) - len(bad) < min_views or len(views) - len(keep) + len(bad) > len(views) // 2:
            break
        rep["dropped_views"] += [views[j][0] for j in bad]; keep = [j for j in keep if j not in bad]
    if std is None:
        std = _std_from_jacobian(intr, obj, img, rvecs, tvecs)
    normals = np.array([cv2.Rodrigues(np.asarray(rv, float))[0][:, 2] for rv in rvecs])
    ang = np.degrees(np.arccos(np.clip(normals @ normals.T, -1, 1)))
    adj = (ang >= min_tilt_deg).astype(int)
    pts = np.concatenate(img); cells = {(int(u * 8 // w), int(v * 6 // h)) for u, v in pts if 0 <= u < w and 0 <= v < h}
    K = intr.K; fx, fy, cx, cy = K[0, 0], K[1, 1], K[0, 2], K[1, 2]
    rep.update(n_used=len(keep), rms_px=_num(rms), per_view_rms_px=[_num(round(e, 4)) for e in per_view], std_px=dict(zip(("fx", "fy", "cx", "cy"), map(_num, std))),
               max_tilt_deg=float(ang.max()), tilt_ok=bool(((adj @ adj) * adj).any()), K=K.tolist(), dist=intr.dist.tolist(), flags=flags,
               coverage=len(cells) / 48.0, max_radius_frac=float(np.hypot(*(pts - [cx, cy]).T).max() / np.hypot(max(cx, w - 1 - cx), max(cy, h - 1 - cy))))
    rich = _fit_model("rational", obj, img, (w, h)) if model == "pinhole" else None
    if rich is not None:  # a structurally inadequate model (e.g. pinhole on a GoPro-class lens) still fits the data to a few 0.1 px
        rep["rms_px_rational"] = _num(_rms(rich[0], obj, img, rich[1], rich[2])[0])
    if not rms <= max_rms_px:
        rep["reason"] = f"RMS {rms:.2f} px > {max_rms_px} px (wrong board spec, blur, or lens model {model!r} too simple)"
    elif rep.get("rms_px_rational") is not None and rms > 1.1 * rep["rms_px_rational"] + 0.02:
        rep["reason"] = (f"pinhole model too simple for this lens: RMS {rms:.3f} px vs {rep['rms_px_rational']:.3f} px with model='rational' "
                         "(biased focal length / principal point); recalibrate with model='rational' or 'fisheye'")
    elif not rep["tilt_ok"]:
        rep["reason"] = (f"insufficient tilt diversity: no 3 views with board normals >= {min_tilt_deg} deg apart (max {ang.max():.1f} deg); "
                         "tilt the board (or camera) in different directions")
    elif not (std[0] <= max_rel_std_f * fx and std[1] <= max_rel_std_f * fy and std[2] <= max_std_c_frac * w and std[3] <= max_std_c_frac * h):
        rep["reason"] = f"poorly constrained intrinsics: 1-sigma fx {std[0]:.1f} fy {std[1]:.1f} cx {std[2]:.1f} cy {std[3]:.1f} px"
    elif not (0.2 * w <= cx <= 0.8 * w and 0.2 * h <= cy <= 0.8 * h):
        rep["reason"] = f"principal point ({cx:.0f}, {cy:.0f}) implausibly far from the image centre"
    else:
        rep["ok"] = True; intr.rms_px = rms
        return intr, rep
    return None, rep


def calibrate_intrinsics(frames: list[np.ndarray], spec: BoardSpec, model: str = "pinhole", **kw) -> Intrinsics | None:
    """Intrinsics (source="board") from >= 8 RAW board views with diverse tilts; None when the views cannot determine
    them. See calibrate_intrinsics_report for the checks and the reason."""
    return calibrate_intrinsics_report(frames, spec, model, **kw)[0]


