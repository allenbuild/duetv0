@dataclass(frozen=True)
class BoardSpec:
    """ChArUco board. square_m / marker_m: printed edge lengths in METRES (range-checked, so 50 meaning mm fails loudly).
    legacy=True for boards generated by OpenCV < 4.6 or 'legacy' online generators (layouts differ when squares_y is even).
    dictionary: name of a cv2.aruco predefined dictionary."""
    squares_x: int = 7
    squares_y: int = 5
    square_m: float = 0.05
    marker_m: float = 0.037
    legacy: bool = False
    dictionary: str = "DICT_5X5_100"

    def __post_init__(self):
        for n in ("squares_x", "squares_y"):
            v = getattr(self, n)
            if isinstance(v, bool) or not float(v).is_integer() or not 3 <= int(v) <= 100:
                raise GeometryError(f"BoardSpec.{n}={v!r}: expected an integer 3-100")
        _in_range(self.square_m, "BoardSpec.square_m", 0.005, 1.0, " (metres)")
        _in_range(self.marker_m, "BoardSpec.marker_m", 0.002, 1.0, " (metres)")
        if not float(self.marker_m) < float(self.square_m):
            raise GeometryError(f"BoardSpec.marker_m={self.marker_m} must be smaller than square_m={self.square_m}")
        if not isinstance(self.dictionary, str) or not isinstance(getattr(cv2.aruco, self.dictionary, None), int):
            raise GeometryError(f"BoardSpec.dictionary={self.dictionary!r} is not a cv2.aruco predefined dictionary")

    def board(self) -> cv2.aruco.CharucoBoard:
        _require_charuco_opencv()
        b = cv2.aruco.CharucoBoard((int(self.squares_x), int(self.squares_y)), float(self.square_m), float(self.marker_m),
                                   cv2.aruco.getPredefinedDictionary(getattr(cv2.aruco, self.dictionary)))
        if self.legacy:
            b.setLegacyPattern(True)
        return b

    def corners_m(self) -> np.ndarray:
        """[n_inner, 3] board-frame positions of the ChArUco corners, indexed by ChArUco corner id."""
        return _board_corners(self).copy()


@lru_cache(maxsize=32)
def _board_corners(spec: BoardSpec) -> np.ndarray:
    return np.asarray(spec.board().getChessboardCorners(), float).reshape(-1, 3)


_LOCAL = threading.local()  # OpenCV detectors are cached per thread (not documented as thread-safe)


def _charuco_detector(spec: BoardSpec):
    cache = getattr(_LOCAL, "charuco", None)
    if cache is None:
        cache = _LOCAL.charuco = {}
    if spec not in cache:
        cache[spec] = cv2.aruco.CharucoDetector(spec.board())
    return cache[spec]


def detect_board(gray: np.ndarray, spec: BoardSpec, min_corners: int = 6):
    """ChArUco corners in a RAW image: (charuco_corners [N,1,2] float32 px, charuco_ids [N,1] int32) or (None, None)."""
    _require_charuco_opencv()
    corners, ids, _, _ = _charuco_detector(spec).detectBoard(_as_gray(gray, "detect_board image"))
    if corners is None or ids is None or len(ids) < min_corners or not np.isfinite(corners).all():
        return None, None
    if len(corners) != len(ids):
        raise RuntimeError(f"ChArUco detector returned {len(corners)} corners for {len(ids)} ids (OpenCV {cv2.__version__})")
    return corners, ids


def _num(x) -> float | None:
    """JSON-safe float (None for NaN / inf)."""
    return float(x) if x is not None and np.isfinite(x) else None


def _minor_extent(xy: np.ndarray) -> float:
    """RMS distance of 2-D points from their best-fit line (0 for collinear points)."""
    if len(xy) < 3:
        return 0.0
    return float(np.linalg.svd(xy - xy.mean(0), compute_uv=False)[1] / np.sqrt(len(xy)))


