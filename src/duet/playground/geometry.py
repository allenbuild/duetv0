"""Metric geometry for the playground: board calibration, tag poses, camera registration, triangulation.

Units: metres for every length (board squares, tag sizes, translations); pixels for image coordinates, with OpenCV's
convention that integer coordinates are pixel CENTRES ((0, 0) = centre of the top-left pixel).

Frames (verified by rendering at known poses on OpenCV 4.8-5.0 and pupil-apriltags 1.0; tests/test_playground_geometry.py):
- T_a_b maps b-frame coordinates to a-frame coordinates: p_a = T_a_b @ p_b (4x4, rotation + translation in metres).
- Camera: OpenCV axes, X right, Y down, Z forward along the optical axis. A camera pose is stored as T_world_cam
  (camera -> world; its translation is the camera centre); OpenCV's (rvec, tvec) is T_cam_world (X_cam = R X_world + t).
- World = the ChArUco board frame: origin at the TOP-LEFT outer corner of the printed board (as generated by
  CharucoBoard.generateImage and seen from the front), X along the squares_x edge (right), Y along the squares_y edge
  (down the page), Z = X x Y pointing INTO the board. Cameras that see the board are at Z < 0; for a board lying face-up
  on a table +Z points down into the table, so "above the table" is Z < 0. The first inner corner is (square_m, square_m, 0).
- AprilTag frame (pupil-apriltags = AprilTag 3): origin at the tag centre, X right, Y down, Z INTO the tag face, for the
  tag seen upright as in the official bitmaps (AprilRobotics apriltag-imgs; cv2.aruco's DICT_APRILTAG_36h11 images are those
  bitmaps rotated 180 deg). Same convention as the board: a tag printed upright on the board plane has R_world_tag = I.
  tag_size_m = edge of the BLACK border square (8 of the 10 cells of the official image, white quiet zone excluded).
- Head tag: T_tag_headcam = the head camera's pose in the tag frame (head-camera coords -> tag coords), so
  T_world_headcam = T_world_fixedcam @ T_fixedcam_tag @ T_tag_headcam (head_pose_from_tag).

Intrinsics carry the image size they belong to; functions taking an image assert it has that size (Intrinsics.scaled_to
converts e.g. a native 1920x1080 calibration to 640x360 extracted frames). Lens models: "pinhole" (OpenCV k1 k2 p1 p2
[k3]), "rational" (OpenCV 8/12/14 coefficients, CALIB_RATIONAL_MODEL) and "fisheye" (cv2.fisheye Kannala-Brandt k1..k4;
equidistant when all are zero). Wide lenses (GoPro-class) need "rational" or "fisheye". Detections are made on RAW
(distorted) images; points are undistorted with a converged solve (undistort_points) and returned in raw pixels.
Invalid inputs raise GeometryError; degenerate measurements return None (or NaN) instead of a confident wrong answer.
"""
from __future__ import annotations

import re
import threading
from dataclasses import dataclass
from functools import lru_cache
from itertools import combinations

import cv2
import numpy as np

from duet.geometry.transforms import rigid_matrix_errors

ARUCO_DICT = cv2.aruco.DICT_5X5_100
LENS_MODELS = ("pinhole", "rational", "fisheye")
_CRITERIA = (cv2.TERM_CRITERIA_COUNT | cv2.TERM_CRITERIA_EPS, 100, 1e-12)  # iterative undistortion: converge, don't stop at 5
_MIN_DEPTH_M = 0.01


class GeometryError(ValueError, AssertionError):
    """Invalid geometric input (image size vs intrinsics, non-rigid transform, implausible metric size, bad shapes).
    Subclasses both ValueError and AssertionError so callers written against either wording of the contract catch it."""


def _in_range(x, name: str, lo: float, hi: float, hint: str = "") -> float:
    v = float(x)
    if not (np.isfinite(v) and lo <= v <= hi):
        raise GeometryError(f"{name}={x!r} outside [{lo}, {hi}]{hint}")
    return v


def _as_gray(img, what: str = "image") -> np.ndarray:
    a = np.asarray(img) if img is not None else np.zeros(0)
    if a.ndim == 3 and a.shape[2] in (3, 4):
        a = cv2.cvtColor(a, cv2.COLOR_BGR2GRAY if a.shape[2] == 3 else cv2.COLOR_BGRA2GRAY)
    if a.ndim != 2 or a.size == 0 or a.dtype != np.uint8:
        raise GeometryError(f"{what}: expected a non-empty uint8 grayscale image, got shape {a.shape} dtype {a.dtype}")
    return np.ascontiguousarray(a)


def _cv_version() -> tuple[int, int]:
    m = re.match(r"(\d+)\.(\d+)", cv2.__version__)
    return (int(m.group(1)), int(m.group(2))) if m else (0, 0)


def _require_charuco_opencv() -> None:
    if _cv_version() < (4, 8):
        raise RuntimeError(f"ChArUco needs OpenCV >= 4.8 (found {cv2.__version__}): 4.7's CharucoBoard API treats ChArUco corners as "
                           "marker corners and returns wrong object points (130 px errors accepted); upgrade opencv-python")


