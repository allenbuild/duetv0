def register_cameras_from_board(views: dict[str, tuple[np.ndarray, Intrinsics]], spec: BoardSpec, max_err_px: float = 3.0) -> dict[str, tuple[np.ndarray, float]]:
    """One RAW grayscale frame per camera that shows the board -> name -> (T_world_cam, mean reprojection px) for the
    cameras whose board pose passes (board_pose checks, error <= max_err_px). World = board frame. The frames must be
    simultaneous, or the board static between them, for the cameras to share one world."""
    out = {}
    for name, (gray, intr) in views.items():
        r = board_pose(gray, intr, spec, max_err_px=max_err_px)
        if r is not None:
            T_cam_board, err = r; out[name] = (inv(T_cam_board), err)  # T_world_cam with world == board
    return out
